#!/usr/bin/env python3
"""Generate the measured effect duration table from a sweep.

    python3 HapticLab/Tools/make_effect_table.py <run-dir> > \
        HapticLab/Software/Libs/Header/EffectTable.hpp

Every timing this app derives hangs off one number per effect. Before this the
number was `kNominalEffectMs`, a ceiling of 1000 ms for every effect, which made
the presentation window nearly four seconds for patterns that finish in a tenth
of that. The sweep measures them, so the app should use what was measured.

The header is generated rather than typed so that the run it came from, the
criterion, and the spread are all in the file beside the numbers. Regenerate it
from a newer sweep rather than editing it.

An effect with no onset in any repeat is written at the nominal ceiling instead
of zero: those indices are disqualified elsewhere, and a pattern that reaches one
anyway should oversize its window rather than undersize it.
"""
import csv
import os
import statistics
import sys

NOMINAL_MS = 1000

# Kept in step with `kPresentationMarginMs` in Protocol.hpp by the test that
# reads both, not by hand.
MARGIN_MS = 400


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: make_effect_table.py <run-dir>")
    run = sys.argv[1]
    leaf = "effects-rebuilt.csv"
    if not os.path.exists(os.path.join(run, leaf)):
        leaf = "effects.csv"
    rows = list(csv.DictReader(open(os.path.join(run, leaf))))
    if not rows:
        raise SystemExit("%s/%s is empty" % (run, leaf))

    by = {}
    for r in rows:
        if int(r["onset_us"]) < 0:
            continue
        by.setdefault(int(r["effect"]), []).append(int(r["duration_us"]) / 1000.0)

    schema = rows[0]["schema"]
    run_id = rows[0]["run_id"]
    lo = min(int(r["effect"]) for r in rows)
    hi = max(int(r["effect"]) for r in rows)
    repeats = len({r["repeat"] for r in rows})
    worst = max(((max(v) - min(v)), e) for e, v in by.items()) if by else (0, 0)

    out = sys.stdout.write
    out("#ifndef HAPTICLAB_EFFECTTABLE_HPP\n#define HAPTICLAB_EFFECTTABLE_HPP\n\n")
    out('#include "Patterns.hpp"\n\n')
    out("/// GENERATED by Tools/make_effect_table.py. Do not edit; regenerate.\n")
    out("///\n")
    out("/// Source: run `%s`, schema %s, `%s`, effects %d to %d at\n"
        % (run_id, schema, leaf, lo, hi))
    out("/// %d repeats each. Each figure is the median across those repeats of the\n" % repeats)
    out("/// burst duration measured by `SweepStats.hpp`, which ends an effect at a\n")
    out("/// tenth of its own peak so the ring-down is not counted as drive.\n")
    out("///\n")
    out("/// The two effects that name a duration are what validate the figures: 15\n")
    out("/// and 16 come out at %.1f and %.1f ms against a declared 750 and 1000.\n"
        % (statistics.median(by.get(15, [0])), statistics.median(by.get(16, [0]))))
    wide = sorted(((max(v) - min(v)), e) for e, v in by.items() if max(v) - min(v) > MARGIN_MS)
    out("/// The median is used rather than the slowest repeat, because the table is\n")
    out("/// a best estimate and `kPresentationMarginMs` is the safety. The widest\n")
    out("/// disagreement between repeats anywhere here is %.0f ms, on effect %d.\n"
        % (worst[0], worst[1]))
    if wide:
        out("/// **These effects disagree by more than that margin**, so a pattern\n")
        out("/// built on one can outrun its own presentation window: %s.\n"
            % ", ".join(str(e) for _, e in wide))
    else:
        out("/// No effect disagrees by more than that margin.\n")
    out("///\n")
    out("/// Measured off the wrist. The wrist damps: the same effects measured on\n")
    out("/// one came out a median of 10 ms shorter and about a quarter quieter\n")
    out("/// (Docs/LEDGER.md row S20). Off-wrist figures are therefore both the\n")
    out("/// quieter measurement and the conservative one for sizing a window.\n")
    out("namespace Haptic {\n\n")
    out("/// Every effect's measured duration in ms, indexed by effect number.\n")
    out("inline EffectDurations measuredDurations()\n{\n")
    out("    EffectDurations d {};\n")
    out("    for (size_t i = 0; i <= kMaxEffect; i++) {\n")
    out("        d.ms[i] = kNominalEffectMs;\n")
    out("    }\n")
    for e in sorted(by):
        out("    d.ms[%3d] = %4d;\n" % (e, int(round(statistics.median(by[e])))))
    out("    d.measured = true;\n    return d;\n}\n\n")
    out("} // namespace Haptic\n\n#endif // HAPTICLAB_EFFECTTABLE_HPP\n")


if __name__ == "__main__":
    main()
