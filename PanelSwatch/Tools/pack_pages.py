#!/usr/bin/env python3
"""Packs 240x240 ABGR2222 frames (*.raw, sorted by name) into Software/Apps/CustomGUI/Pages.hpp.

    python3 Tools/pack_pages.py <dir of .raw frames>

Run-length pairs (count 1..255, byte), decoded straight into the framebuffer.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Software", "Apps", "CustomGUI", "Pages.hpp")
PIXELS = 240 * 240


def rle(b):
    out, i = bytearray(), 0
    while i < len(b):
        j = i
        while j < len(b) and b[j] == b[i] and j - i < 255:
            j += 1
        out += bytes([j - i, b[i]])
        i = j
    return out


def main():
    src = sys.argv[1]
    names = sorted(f for f in os.listdir(src) if f.endswith(".raw"))
    parts, total = [], 0
    for k, n in enumerate(names):
        raw = open(os.path.join(src, n), "rb").read()
        assert len(raw) == PIXELS, f"{n} is {len(raw)} bytes, not {PIXELS}"
        r = rle(raw)
        total += len(r)
        rows = ",\n".join("    " + ", ".join(str(x) for x in r[i:i + 24]) for i in range(0, len(r), 24))
        parts.append(f"// {n}\nstatic const uint8_t kPage{k}[] = {{\n{rows}\n}};\n")
    table = ", ".join(f"{{kPage{k}, sizeof(kPage{k})}}" for k in range(len(names)))
    with open(OUT, "w") as f:
        f.write(f"""// Generated by Tools/pack_pages.py from {len(names)} frames ({total} bytes); do not edit.
#ifndef PAGES_HPP
#define PAGES_HPP

#include <cstddef>
#include <cstdint>

namespace Pages
{{

{chr(10).join(parts)}
struct Page {{
    const uint8_t *data;
    size_t         size;
}};

static const Page kAll[] = {{{table}}};
static constexpr uint32_t kCount = sizeof(kAll) / sizeof(kAll[0]);

/// Expands page `n`; pixels past the encoded data stay as they were.
inline void decode(uint32_t n, uint8_t *out, uint32_t pixels)
{{
    const Page &p = kAll[n % kCount];
    uint32_t    at = 0;
    for (size_t i = 0; i + 1 < p.size && at < pixels; i += 2) {{
        for (uint8_t c = 0; c < p.data[i] && at < pixels; ++c) {{
            out[at++] = p.data[i + 1];
        }}
    }}
}}

}} // namespace Pages

#endif // PAGES_HPP
""")
    print(f"wrote {OUT}: {len(names)} pages, {total} bytes")


main()
