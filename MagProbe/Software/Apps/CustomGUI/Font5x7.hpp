constexpr uint8_t kGlyphCount = static_cast<uint8_t>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));

static_assert(kGlyphCount == (kLastChar - kFirstChar + 1),
              "the glyph table and the character range have to agree, or every "
              "glyph past the gap renders as the wrong letter");

/// Drawn for anything outside the table: a hollow box, which is visibly not a
/// letter. Rendering an unmapped character as a space would hide the fact that
/// the string reaching the screen is not the string that was written.
constexpr uint8_t kMissing[kWidth] = {0x7F, 0x41, 0x41, 0x41, 0x7F};

/// Columns for one character. Lowercase folds onto uppercase.
inline const uint8_t* glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        c = static_cast<char>(c - 'a' + 'A');
    }
    if (c < kFirstChar || c > kLastChar) {
        return kMissing;
    }
    return kGlyphs[static_cast<uint8_t>(c - kFirstChar)];
}

