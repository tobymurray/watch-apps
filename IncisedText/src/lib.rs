/// One glyph of a [`Face`]: where its pixels start in the face's bitstream and how to place it.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct Node {
    /// Byte offset of the glyph's first pixel in [`Face::data`].
    pub off: u32,
    pub cp: u16,
    /// Ink width in pixels; 0 for a glyph with no ink.
    pub w: u8,
    /// Ink height in pixels; 0 for a glyph with no ink.
    pub h: u8,
    /// Rows from the baseline up to the top of the ink.
    pub top: i8,
    /// Columns from the pen to the left edge of the ink.
    pub left: i8,
    /// Columns the pen moves after this glyph.
    pub adv: u8,
    /// Reserved; 0.
    pub flags: u8,
}

const _: () = assert!(core::mem::size_of::<Node>() == 12);

/// One weight at one pixel size over one character set, generated by `Tools/atlas.py`.
pub struct Face {
    /// Em size the glyphs were rendered at, in pixels.
    pub px: u8,
    /// Rows the face may use above the baseline.
    pub ascent: u8,
    /// Rows the face may use below the baseline.
    pub descent: u8,
    /// Bit 0: hard-aliased, so every level is 0 or 3.
    pub flags: u8,
    pub nodes: &'static [Node],
    pub data: &'static [u8],
}

/// What a string takes up, in pixels along the baseline from the pen's start.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[non_exhaustive]
pub struct Measure {
    /// Sum of advances: what alignment and wrapping use.
    pub advance: i32,
    /// Leftmost inked column relative to the pen's start; 0 for an empty string.
    pub ink_left: i32,
    /// One past the rightmost inked column; 0 for an empty string.
    pub ink_right: i32,
    /// Topmost inked row relative to the baseline, negative above it; 0 for an empty string.
    pub ink_top: i32,
    /// One past the bottommost inked row relative to the baseline; 0 for an empty string.
    pub ink_bottom: i32,
    /// Characters that had no glyph and were drawn as a box, saturating.
    pub missing: u8,
}

/// Where one character of a string lands, in the same columns [`Face::draw`] would put it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct Placed {
    /// The character after composition, as [`chars`] yields it.
    pub ch: char,
    /// Column where this character's pen starts.
    pub pen: i32,
    /// Columns the pen moves after this character.
    pub advance: i32,
    /// Leftmost inked column; equal to `ink_right` for a character with no ink.
    pub ink_left: i32,
    /// One past the rightmost inked column.
    pub ink_right: i32,
    /// The face has no glyph for `ch`, so it is drawn as a box.
    pub missing: bool,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Align {
    Left,
    Center,
    Right,
}

/// A colour that a glyph's partial coverage can be blended in.
pub trait Ink: Copy {
    /// This ink over `ground` at coverage `level`, 0 (none) to 3 (full).
    fn shade(self, ground: Self, level: u8) -> Self;
}

#[cfg(feature = "abgr2222")]
impl Ink for inscribed_disc::Abgr2222 {
    fn shade(self, ground: Self, level: u8) -> Self {
        inscribed_disc::color::shade(self, ground, level)
    }
}

/// How a run of text is coloured and where its advance sits relative to the `x` it is drawn at.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Style<C> {
    pub ink: C,
    /// What a partially covered pixel is blended toward: whatever the screen already holds.
    pub ground: C,
    pub align: Align,
}

impl<C> Style<C> {
    pub fn new(ink: C, ground: C, align: Align) -> Self {
        Style { ink, ground, align }
    }

    /// The pen starts at `x`.
    pub fn left(ink: C, ground: C) -> Self {
        Style::new(ink, ground, Align::Left)
    }

    /// The advance is centred on `x`.
    pub fn centered(ink: C, ground: C) -> Self {
        Style::new(ink, ground, Align::Center)
    }

    /// The advance ends at `x`.
    pub fn right(ink: C, ground: C) -> Self {
        Style::new(ink, ground, Align::Right)
    }
}

fn is_combining(c: char) -> bool {
    ('\u{0300}'..='\u{036F}').contains(&c)
}

fn compose(base: char, mark: char) -> Option<char> {
    let (b, m) = (base as u32, mark as u32);
    if b > 0xFFFF || m > 0xFFFF {
        return None;
    }
    compose::COMPOSE
        .binary_search_by_key(&(b as u16, m as u16), |&(cb, cm, _)| (cb, cm))
        .ok()
        .and_then(|i| char::from_u32(compose::COMPOSE[i].2 as u32))
}

/// The characters of `text` as the face will look them up: a base letter followed by a combining
/// mark becomes its precomposed form when Latin has one; otherwise both pass through unchanged and
/// the mark draws as a missing glyph on its own.
pub fn chars(text: &str) -> impl Iterator<Item = char> + '_ {
    let mut it = text.chars().peekable();
    core::iter::from_fn(move || {
        let c = it.next()?;
        if let Some(&next) = it.peek() {
            if is_combining(next) {
                if let Some(composed) = compose(c, next) {
                    it.next();
                    return Some(composed);
                }
            }
        }
        Some(c)
    })
}

enum Glyph<'f> {
    Node(&'f Node),
    /// A one-pixel hollow box: visible, never a plausible wrong letter.
    Missing { w: i32, h: i32, adv: i32 },
}

impl Glyph<'_> {
    /// Columns from the pen, rows from the baseline (negative above it), and the advance.
    fn bounds(&self) -> (i32, i32, i32, i32, i32) {
        match *self {
            Glyph::Node(n) => {
                let (left, top) = (n.left as i32, -(n.top as i32));
                (left, left + n.w as i32, top, top + n.h as i32, n.adv as i32)
            }
            Glyph::Missing { w, h, adv } => (0, w, -h, 0, adv),
        }
    }
}

impl Face {
    pub fn glyph(&self, c: char) -> Option<&Node> {
        let cp = c as u32;
        if cp > 0xFFFF {
            return None;
        }
        self.nodes
            .binary_search_by_key(&(cp as u16), |n| n.cp)
            .ok()
            .map(|i| &self.nodes[i])
    }

    /// Whether every character of `text` has a glyph, after composition.
    pub fn covers(&self, text: &str) -> bool {
        self.uncovered(text).next().is_none()
    }

    /// The characters of `text` this face has no glyph for, after composition, in order and
    /// repeated as often as they occur.
    pub fn uncovered<'a>(&'a self, text: &'a str) -> impl Iterator<Item = char> + 'a {
        chars(text).filter(move |&c| self.glyph(c).is_none())
    }

    /// Every character this face has a glyph for, in code point order.
    pub fn covered(&self) -> impl Iterator<Item = char> + '_ {
        self.nodes.iter().filter_map(|n| char::from_u32(n.cp as u32))
    }

    /// Ascent plus descent: the rows one line of this face may touch.
    pub fn line_height(&self) -> i32 {
        self.ascent as i32 + self.descent as i32
    }

    fn lookup(&self, c: char) -> Glyph<'_> {
        match self.glyph(c) {
            Some(n) => Glyph::Node(n),
            None => {
                let px = self.px as i32;
                let w = (px * 3 / 5).max(3);
                Glyph::Missing { w, h: (px * 7 / 10).max(3), adv: w + (px / 10).max(1) }
            }
        }
    }

    pub fn measure(&self, text: &str) -> Measure {
        let mut m = Measure::default();
        let mut first = true;
        for c in chars(text) {
            let glyph = self.lookup(c);
            if let Glyph::Missing { .. } = glyph {
                m.missing = m.missing.saturating_add(1);
            }
            let (left, right, top, bottom, adv) = glyph.bounds();
            if right > left {
                let (l, r) = (m.advance + left, m.advance + right);
                if first {
                    (m.ink_left, m.ink_right, m.ink_top, m.ink_bottom) = (l, r, top, bottom);
                    first = false;
                } else {
                    m.ink_left = m.ink_left.min(l);
                    m.ink_right = m.ink_right.max(r);
                    m.ink_top = m.ink_top.min(top);
                    m.ink_bottom = m.ink_bottom.max(bottom);
                }
            }
            m.advance += adv;
        }
        m
    }

    fn placed<'a>(&'a self, text: &'a str, mut pen: i32) -> impl Iterator<Item = (Placed, Glyph<'a>)> + 'a {
        chars(text).map(move |ch| {
            let glyph = self.lookup(ch);
            let (left, right, _, _, advance) = glyph.bounds();
            let (ink_left, ink_right) = if right > left { (pen + left, pen + right) } else { (pen, pen) };
            let missing = matches!(glyph, Glyph::Missing { .. });
            let placed = Placed { ch, pen, advance, ink_left, ink_right, missing };
            pen += advance;
            (placed, glyph)
        })
    }

    /// Each character of `text` where [`Face::draw`] would put it at `x` with `align`.
    pub fn layout<'a>(&'a self, text: &'a str, x: i32, align: Align) -> impl Iterator<Item = Placed> + 'a {
        let advance = if align == Align::Left { 0 } else { self.measure(text).advance };
        self.placed(text, start(x, advance, align)).map(|(p, _)| p)
    }

    fn level(&self, node: &Node, col: i32, row: i32) -> u8 {
        let i = node.off as usize * 4 + (row * node.w as i32 + col) as usize;
        (self.data[i / 4] >> (2 * (i % 4))) & 3
    }

    /// Draws `text` on `baseline`, placed at `x` as the style's alignment says, and returns what
    /// it measured.
    pub fn draw<D>(
        &self,
        target: &mut D,
        text: &str,
        x: i32,
        baseline: i32,
        style: Style<D::Color>,
    ) -> Result<Measure, D::Error>
    where
        D: DrawTarget,
        D::Color: Ink,
    {
        let m = self.measure(text);
        let ramp = [
            style.ink.shade(style.ground, 1),
            style.ink.shade(style.ground, 2),
            style.ink.shade(style.ground, 3),
        ];
        let area = target.bounding_box();
        let (area_left, area_top) = (area.top_left.x, area.top_left.y);
        let (area_right, area_bottom) = (area_left + area.size.width as i32, area_top + area.size.height as i32);
        for (p, glyph) in self.placed(text, start(x, m.advance, style.align)) {
            let (_, _, top, bottom, _) = glyph.bounds();
            let outside = p.ink_right <= area_left
                || p.ink_left >= area_right
                || baseline + bottom <= area_top
                || baseline + top >= area_bottom;
            if p.ink_left == p.ink_right || outside {
                continue;
            }
            let pen = p.pen;
            match glyph {
                Glyph::Node(n) => {
                    let x0 = pen + n.left as i32;
                    let y0 = baseline - n.top as i32;
                    let (w, h) = (n.w as i32, n.h as i32);
                    target.draw_iter((0..w * h).filter_map(|i| {
                        match self.level(n, i % w, i / w) {
                            0 => None,
                            level => Some(Pixel(
                                Point::new(x0 + i % w, y0 + i / w),
                                ramp[level as usize - 1],
                            )),
                        }
                    }))?;
                }
                Glyph::Missing { w, h, .. } => {
                    let y0 = baseline - h;
                    let top = (0..w).map(move |i| (pen + i, y0));
                    let bottom = (0..w).map(move |i| (pen + i, baseline - 1));
                    let left = (0..h).map(move |j| (pen, y0 + j));
                    let right = (0..h).map(move |j| (pen + w - 1, y0 + j));
                    target.draw_iter(
                        top.chain(bottom)
                            .chain(left)
                            .chain(right)
                            .map(|(x, y)| Pixel(Point::new(x, y), style.ink)),
                    )?;
                }
            }
        }
        Ok(m)
    }

    /// [`Face::draw`] with the line's top at `top` instead of its baseline.
    pub fn draw_top<D>(
        &self,
        target: &mut D,
        text: &str,
        x: i32,
        top: i32,
        style: Style<D::Color>,
    ) -> Result<Measure, D::Error>
    where
        D: DrawTarget,
        D::Color: Ink,
    {
        self.draw(target, text, x, top + self.ascent as i32, style)
    }

    /// Greedy word wrap against `max_width`, filling `lines` in order. Returns how many lines the
    /// whole text needs, which exceeds `lines.len()` when it did not fit; a word wider than the
    /// width sits alone on its line rather than being split.
    pub fn wrap<'t>(&self, text: &'t str, max_width: i32, lines: &mut [&'t str]) -> usize {
        let mut count = 0;
        let mut line_start = 0usize;
        let mut line_end = 0usize;
        let emit = |lines: &mut [&'t str], s: &'t str, count: &mut usize| {
            if s.is_empty() {
                return;
            }
            if *count < lines.len() {
                lines[*count] = s;
            }
            *count += 1;
        };
        let word_ends = text
            .char_indices()
            .filter(|&(_, c)| c == ' ')
            .map(|(i, _)| i)
            .chain(core::iter::once(text.len()));
        for word_end in word_ends {
            if word_end <= line_end {
                continue;
            }
            let candidate = text[line_start..word_end].trim();
            if self.measure(candidate).advance <= max_width || line_end == line_start {
                line_end = word_end;
            } else {
                emit(lines, text[line_start..line_end].trim(), &mut count);
                line_start = line_end + 1;
                line_end = word_end.max(line_start);
            }
        }
        if line_start < text.len() {
            emit(lines, text[line_start..].trim(), &mut count);
        }
        count
    }
}

/// Where the pen starts for an advance placed at `x` as `align` says.
fn start(x: i32, advance: i32, align: Align) -> i32 {
    match align {
        Align::Left => x,
        Align::Center => x - advance / 2,
        Align::Right => x - advance,
    }
}

/// The first of `faces` whose advance for `text` fits `max_width`: the size ladder.
pub fn pick<'f>(faces: &[&'f Face], text: &str, max_width: i32) -> Option<&'f Face> {
    faces.iter().copied().find(|f| f.measure(text).advance <= max_width)
}

